"""Unit tests for investigation domain models and markdown serialization."""

from reliability_lab.investigation.models import (
    ComparisonTopic,
    EvidenceFinding,
    InvestigationRecord,
    InvestigationReport,
)


def test_evidence_finding_serialization():
    finding = EvidenceFinding(
        finding_id="f1",
        investigation_id="inv-123",
        topic_name="Throughput vs Latency",
        doc_id="doc-1",
        doc_title="FlashAttention Paper",
        chunk_id="chk_001",
        page_number=4,
        claim="FlashAttention achieves 2-4x speedup with exact attention.",
        supporting_passage="We observe 2-4x speedup across standard sequence lengths.",
        relationship="supports",
        confidence=0.95,
        methodology_notes="Measured on A100 GPUs with sequence length 2048.",
    )

    data = finding.to_dict()
    assert data["finding_id"] == "f1"
    assert data["relationship"] == "supports"
    assert data["chunk_id"] == "chk_001"
    assert data["page_number"] == 4

    restored = EvidenceFinding.from_dict(data)
    assert restored.finding_id == finding.finding_id
    assert restored.doc_id == finding.doc_id
    assert restored.claim == finding.claim
    assert restored.confidence == 0.95


def test_investigation_report_markdown_generation():
    f1 = EvidenceFinding(
        finding_id="f1",
        investigation_id="inv-1",
        topic_name="Memory Footprint",
        doc_id="doc-1",
        doc_title="FlashAttention",
        chunk_id="chk_01",
        page_number=3,
        claim="Reduces memory from O(N^2) to O(N).",
        supporting_passage="IO-aware design yields linear memory footprint.",
        relationship="supports",
        confidence=0.98,
        methodology_notes="Evaluated with sequence length up to 64k.",
    )

    f2 = EvidenceFinding(
        finding_id="f2",
        investigation_id="inv-1",
        topic_name="Memory Footprint",
        doc_id="doc-2",
        doc_title="Standard Transformer",
        chunk_id="chk_02",
        page_number=5,
        claim="Standard attention exhibits quadratic O(N^2) memory consumption.",
        supporting_passage="Self-attention matrix computation scales quadratically.",
        relationship="contradicts",
        confidence=0.90,
    )

    topic = ComparisonTopic(
        topic_name="Memory Footprint",
        description="Analysis of memory complexity across context lengths.",
        findings=[f1, f2],
        agreements_summary="Both papers recognize quadratic memory bottlenecks.",
        disagreements_summary="FlashAttention solves this via tiling, unlike baseline.",
        evidence_gaps=["No evaluation on mobile hardware architectures."],
    )

    report = InvestigationReport(
        investigation_id="inv-1",
        title="Transformer Efficiency Investigation",
        query="Compare memory and throughput scaling across attention variants",
        executive_summary="FlashAttention provides substantial memory advantages.",
        documents=[
            {"doc_id": "doc-1", "title": "FlashAttention", "chunk_count": 12},
            {"doc_id": "doc-2", "title": "Standard Transformer", "chunk_count": 15},
        ],
        topics=[topic],
        relationship_counts={"supports": 1, "contradicts": 1, "qualifies": 0},
        total_findings=2,
        methodology_synthesis="Both papers conducted evaluations on NVIDIA A100 SXM4 GPUs.",
        generated_at="2026-11-08T00:00:00Z",
    )

    md = report.to_markdown()
    assert "# STING Investigation Report: Transformer Efficiency Investigation" in md
    assert "## 1. Executive Summary" in md
    assert "FlashAttention provides substantial memory advantages." in md
    assert "## 2. Investigated Document Collection" in md
    assert "FlashAttention" in md
    assert "Standard Transformer" in md
    assert "## 3. Evidence Breakdown" in md
    assert "- **Total Extracted Findings:** 2" in md
    assert "- **Supporting Evidence:** 1" in md
    assert "### 4.1 Memory Footprint" in md
    assert "Both papers recognize quadratic memory bottlenecks." in md
    assert "FlashAttention solves this via tiling" in md
    assert "No evaluation on mobile hardware architectures." in md
    assert "| `SUPPORTS` | FlashAttention | 3 | `chk_01` |" in md
    assert "## 5. Methodology & Context Synthesis" in md
    assert "*Report generated by STING Evidence Intelligence Workbench.*" in md


def test_investigation_record_dataclass():
    rec = InvestigationRecord(
        investigation_id="inv-rec-1",
        title="KV Cache Optimization",
        query="Evaluate PagedAttention vs standard KV cache",
        comparison_aspects=["Memory Fragmentation", "Serving Throughput"],
        document_ids=["doc-a", "doc-b"],
        status="completed",
        created_at="2026-11-08T01:00:00Z",
        completed_at="2026-11-08T01:05:00Z",
        report=None,
    )
    assert rec.investigation_id == "inv-rec-1"
    assert rec.status == "completed"
    assert len(rec.document_ids) == 2
    assert len(rec.aspects) == 2
